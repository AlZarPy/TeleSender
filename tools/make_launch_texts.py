FACTS_REQUIRED = {
    "group1_first": ["13 ноября"],
    "group1_second": ["22 ноября", "19:30", "Андроньевская", "terra_main_bot"],
    "group2_full": ["13 ноября", "22 ноября", "19:30", "Андроньевская", "terra_main_bot"],
}


def ask(model: str) -> dict:
    body = json.dumps({"model": model, "temperature": 0.7, "max_tokens": 4000,
                       "messages": [{"role": "user", "content": BRIEF}]}).encode()
    req = urllib.request.Request(API, data=body, headers={
        "Authorization": f"Bearer {api_key()}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=240) as resp:
        data = json.load(resp)
    text = (data["choices"][0]["message"].get("content") or "").strip()
    start, end = text.find("{"), text.rfind("}")
    return json.loads(text[start:end + 1])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="anthropic/claude-sonnet-5.5")
    args = ap.parse_args()

    try:
        texts = ask(args.model)
    except Exception as exc:  # noqa: BLE001
        print(f"модель не ответила: {type(exc).__name__}: {str(exc)[:200]}")
        return 1

    lines = ["# Тексты под запуск 41-го потока · версия Sonnet 5.5", ""]
    problems = 0
    for key, text in texts.items():
        score = antispam.score(text)
        missing = [f for f in FACTS_REQUIRED.get(key)
                   if f not in text and not (f == "terra_main_bot" and "<ССЫЛКА>" in text)]
        bad_words = [w for w in ("39 мастер", "5 зал", "пяти зал") if w in text.lower()]
        flag = "ок"
        if score["verdict"] == "спам" or missing or bad_words or len(text) > 750:
            flag = "проверить"
            problems += 1
        lines += [f"## {key}", "", "```", text, "```", "",
                  f"спам-скор: {score['points']} ({score['verdict']}) · знаков {len(text)}"
                  + (f" · нет фактов: {', '.join(missing)}" if missing else "")
                  + (f" · лишние слова: {', '.join(bad_words)}" if bad_words else "")
                  + f" · {flag}", ""]
    out = ROOT / "docs" / "launch-texts.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nсохранено: {out} · проблемных: {problems}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
