def seed() -> int:
    """Заливает базовые карточки. Повторный вызов обновляет их."""
    db.init()
    for card in CARDS:
        payload = {k: v for k, v in card.items() if k != "facts_list"}
        payload["facts"] = "\n".join(card.get("facts_list") or [])
        db.fact_upsert(payload)
    return db.facts_count()


def context_for(query: str, limit: int = 4) -> str:
    """Блок фактов для промпта: только релевантные карточки, не весь корпус."""
    cards = db.fact_search(query, limit=limit)
    if not cards:
        return ""
    lines = ["Факты, которыми можно пользоваться (только они):"]
    for c in cards:
        lines.append(f"— {c['title']}: {c['body']}")
    return "\n".join(lines)


_TIME = re.compile(r"\b(\d{1,2})[:.](\d{2})\b")
_DATE = re.compile(r"\b(\d{1,2})\s+(январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)\w*", re.I)
_ADDR = re.compile(r"наб\.?\s*,?\s*(\d+)", re.I)


def allowed_facts() -> set[str]:
    """Все значения из поля `facts` — по ним и только по ним сверяем ответ."""
    db.init()
    out: set[str] = set()
    for row in db.q("SELECT fact_list FROM facts WHERE fact_list<>''"):
        for line in (row["fact_list"] or "").splitlines():
            value = line.strip().lower()
            if value:
                out.add(value)
    return out


def check_numbers(text: str) -> list[dict]:
    """Ищет в ответе числа, которых нет в базе фактов."""
    allowed = allowed_facts()
    issues: list[dict] = []

    for m in _TIME.finditer(text):
        value = f"{m.group(1)}:{m.group(2)}"
        if not any(value in a for a in allowed):
            issues.append({"code": "fact_time", "detail": f"время {value} нет в базе фактов"})

    for m in _DATE.finditer(text):
        found = m.group(0).lower()
        parts = found.split()
        num = parts[0]
        mon = parts[1][:6] if len(parts) > 1 else ""
        if not any(num in a and mon in a for a in allowed):
            issues.append({"code": "fact_date", "detail": f"дата «{m.group(0)}» нет в базе фактов"})

    for m in _ADDR.finditer(text):
        if not any(str(m.group(1)) in a for a in allowed):
            issues.append({"code": "fact_address", "detail": f"дом {m.group(1)} нет в базе фактов"})

    return issues
